// all the Hebrew the nikkud course speaks (recorded by tools/make_audio.py)
export function nikkudTexts() {
  const out = new Set([VOICE.hello, VOICE.turn, VOICE.again, VOICE.done, ...VOICE.good, ...Object.values(PART).map(p => p.say)]);
  for (const s of ['a', 'i', 'e', 'o', 'u']) lettersFor(s).forEach(L => out.add(spoken(L, s)));
  DAGESH_PAIRS.forEach(([, say]) => out.add(say));
  for (const L of LESSONS) {
    L.lines.forEach(t => out.add(t));
    L.words.forEach(w => out.add(w.he));
    (L.demos || []).forEach(d => out.add(d[3]));
    (L.sentences || []).forEach(s => out.add(s[0]));
  }
  out.delete('');
  return [...out];
}
